// Reverse fancy - fancy -> normal (for search / compare)
function unfancy(text) {
  const reverse = {};
  for (const [k, v] of Object.entries(fancyMap)) reverse[v] = k;
  return String(text).split('').map(c => reverse[c] || c).join('');
}

// Make a box - Terminal Hacker style used in menu
function box(text) {
  const lines = String(text).split('\n');
  const top = '╭══〘 💀 MINI-ZYRA 〙══╮';
  const bottom = '╰═══════════════════⊷❍';
  const middle = lines.map(l => `┃✯│ ${l}`).join('\n');
  return `${top}\n${middle}\n${bottom}`;
}

